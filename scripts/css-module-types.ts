// Writes <name>.module.css.d.ts beside every CSS module, listing the classes it exports, so a
// class missing from its CSS fails the typecheck. As in Whereabouts, more simply: classes are
// read with a pattern, leaving out those inside :global(…).
//
// Usage: node scripts/css-module-types.ts. The dev server (vite.config.ts) keeps them current.
import { existsSync, globSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"
import { pathToFileURL } from "node:url"

const SOURCE = "src/**/*.module.css"

const classesOf = (css: string): string[] => {
  const local = css.replace(/\/\*[\s\S]*?\*\//g, "").replace(/:global\([^)]*\)/g, "")
  // Class selectors only: not inside declarations (e.g. "0.5s" or a URL).
  const selectors = local.replace(/\{[^{}]*\}/g, "{}")
  return [...new Set([...selectors.matchAll(/\.([A-Za-z_][\w-]*)/g)].map((m) => m[1] ?? ""))].sort()
}

/** Writes one module's declaration, unless it is already current. */
export const writeDeclaration = (file: string): void => {
  const members = classesOf(readFileSync(file, "utf8")).map((name) => `  readonly ${name}: string`)
  const text = ["// Generated by scripts/css-module-types.ts.", "declare const styles: {", ...members, "}"]
    .concat("export default styles", "")
    .join("\n")
  const target = `${file}.d.ts`
  if (!existsSync(target) || readFileSync(target, "utf8") !== text) writeFileSync(target, text)
}

/** Writes every declaration and drops stale ones. */
export const generateAll = (): void => {
  const modules = new Set(globSync(SOURCE))
  for (const file of modules) writeDeclaration(file)
  for (const declaration of globSync(`${SOURCE}.d.ts`)) {
    if (!modules.has(declaration.slice(0, -".d.ts".length))) rmSync(declaration)
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) generateAll()
